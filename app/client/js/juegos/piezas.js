'use strict';
// Piezas de ajedrez en pixel art (12×12) como SVG, con contorno. Se usan en el Ajedrez.
window.PIEZAS_PIXEL = (() => {
  const S = {
    p: ['............', '.....##.....', '....####....', '....####....', '.....##.....', '....####....', '.....##.....', '.....##.....', '....####....', '...######...', '..########..', '............'],
    n: ['............', '....##......', '...#####....', '..#######...', '..###.###...', '.#####.##...', '.##..####...', '.....####...', '....#####...', '...######...', '..########..', '............'],
    b: ['.....##.....', '....####....', '...##.###...', '...#.####...', '...######...', '....####....', '.....##.....', '....####....', '....####....', '...######...', '..########..', '............'],
    r: ['............', '..##.##.##..', '..########..', '...######...', '...######...', '...######...', '...######...', '...######...', '..########..', '..########..', '.##########.', '............'],
    q: ['.#...##...#.', '.#..####..#.', '.##.####.##.', '.##########.', '..########..', '..########..', '...######...', '....####....', '...######...', '..########..', '.##########.', '............'],
    k: ['.....##.....', '....####....', '.....##.....', '...######...', '..########..', '..###..###..', '..########..', '...######...', '....####....', '...######...', '..########..', '.##########.'],
  };
  const cache = {};
  return (p) => {
    if (cache[p]) return cache[p];
    const t = p.toLowerCase(), blanca = p !== t;
    const filas = S[t];
    const relleno = blanca ? '#f6f1e6' : '#3a3456', brillo = blanca ? '#ffffff' : '#5d5580', borde = '#1e1b2e';
    let fondo = '', cuerpo = '';
    filas.forEach((f, y) => [...f].forEach((ch, x) => {
      if (ch !== '#') return;
      for (const [dx, dy] of [[-1, 0], [1, 0], [0, -1], [0, 1]]) fondo += `<rect x="${x + 1 + dx}" y="${y + 1 + dy}" width="1" height="1"/>`;
      const arriba = y === 0 || filas[y - 1][x] !== '#';
      cuerpo += `<rect x="${x + 1}" y="${y + 1}" width="1" height="1" fill="${arriba ? brillo : relleno}"/>`;
    }));
    cache[p] = `<svg viewBox="0 0 14 14" shape-rendering="crispEdges" aria-hidden="true"><g fill="${borde}">${fondo}</g>${cuerpo}</svg>`;
    return cache[p];
  };
})();
